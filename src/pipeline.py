"""End-to-end run: data, snapshots, cross-validation, holdout, reports.

    python -m src.pipeline           # full run
    python -m src.pipeline --tune    # also re-run the XGBoost grid search

One command reproduces every number in the README. Anything that cannot be
reproduced by this script does not belong in the README.
"""

from __future__ import annotations

import argparse
import logging
import time
import warnings

import joblib
import pandas as pd

from src import config, evaluate, features, metrics, models, visualize
from src.data import build_transactions

warnings.filterwarnings("ignore", category=FutureWarning)
logger = logging.getLogger("pipeline")


def _money(frame: pd.DataFrame, columns: list) -> pd.DataFrame:
    out = frame.copy()
    for col in columns:
        if col in out:
            out[col] = out[col].map(lambda v: f"£{v:,.0f}")
    return out


def _write_report(cv_summary, holdout, seasonality, sweep, importance,
                  calibration, stability, figures, best_name) -> None:
    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    headline = holdout[(holdout["model"] == best_name)
                       & (holdout["split"] == "holdout (Oct+Nov)")].iloc[0]
    baseline = holdout[(holdout["model"] == "recency_baseline")
                       & (holdout["split"] == "holdout (Oct+Nov)")].iloc[0]

    lines = [
        "# Results",
        "",
        "> Generated by `src/pipeline.py`. Every number is reproducible with "
        "`python -m src.pipeline`.",
        "",
        "## Problem",
        "",
        "For each customer with at least one prior order, predict whether they place "
        f"another order within **{config.HORIZON_DAYS} days** of a monthly cutoff. "
        "Snapshots are stacked across nine cutoffs; the last two months are a holdout "
        "that model selection never saw.",
        "",
        "## Headline (holdout: October + November 2011)",
        "",
        f"| Metric | {best_name} | recency rule | difference |",
        "|---|---:|---:|---:|",
        f"| PR-AUC | {headline['pr_auc']:.3f} | {baseline['pr_auc']:.3f} | "
        f"+{headline['pr_auc'] - baseline['pr_auc']:.3f} |",
        f"| ROC-AUC | {headline['roc_auc']:.3f} | {baseline['roc_auc']:.3f} | "
        f"+{headline['roc_auc'] - baseline['roc_auc']:.3f} |",
        f"| Precision@20% | {headline['precision_at_20']:.3f} | "
        f"{baseline['precision_at_20']:.3f} | +{headline['precision_at_20'] - baseline['precision_at_20']:.3f} |",
        f"| Lift@20% | {headline['lift_at_20']:.2f}x | {baseline['lift_at_20']:.2f}x | "
        f"+{headline['lift_at_20'] - baseline['lift_at_20']:.2f} |",
        f"| Brier | {headline['brier']:.3f} | {baseline['brier']:.3f} | "
        f"{headline['brier'] - baseline['brier']:+.3f} |",
        f"| Accuracy | {headline['accuracy']:.3f} | {baseline['accuracy']:.3f} | — |",
        f"| *Accuracy of 'nobody returns'* | *{headline['majority_accuracy']:.3f}* | | |",
        "",
        "The last two rows are the argument against accuracy: the recency rule scores "
        f"**{baseline['accuracy']:.3f}**, which is *below* the "
        f"**{headline['majority_accuracy']:.3f}** you get by predicting that nobody ever "
        "returns — yet it ranks customers well enough to beat random targeting by "
        f"{baseline['lift_at_20']:.2f}x. Accuracy cannot see that, because it grades a "
        "threshold nobody uses on a decision nobody makes.",
        "",
        "## Cross-validation (expanding window, development cutoffs only)",
        "",
        cv_summary.to_markdown(),
        "",
        "## Holdout, per cutoff",
        "",
        holdout[holdout["split"] != "holdout (Oct+Nov)"][
            ["model", "split", "base_rate", "pr_auc", "precision_at_20", "lift_at_20"]
        ].round(3).to_markdown(index=False),
        "",
        "PR-AUC is not comparable across the two months, because it scales with the base "
        "rate (27.4% in October, 34.7% in November). Lift is, which is why it is the "
        "metric quoted to the business.",
        "",
        "## Base rate by cutoff",
        "",
        seasonality.to_markdown(index=False),
        "",
        "## Campaign capacity",
        "",
        _money(sweep, ["revenue", "cost", "net"]).to_markdown(index=False),
        "",
        "## Calibration (holdout, quantile bins)",
        "",
        calibration.to_markdown(index=False),
        "",
        "## Stability after training",
        "",
        stability.to_markdown(index=False),
        "",
        "## Permutation importance (holdout, scored by PR-AUC)",
        "",
        importance.head(15).to_markdown(index=False),
        "",
        "## Figures",
        "",
    ]
    lines += [f"![{p}]({p.replace('reports/', '')})" for p in figures]
    (config.REPORTS_DIR / "results.md").write_text("\n".join(lines), encoding="utf-8")


def run(tune: bool = False) -> None:
    started = time.time()

    logger.info("1/6 transactions")
    transactions = build_transactions()

    logger.info("2/6 snapshots")
    snapshots = features.build_snapshots(transactions)
    feature_names = features.feature_columns(snapshots)
    dev, test = evaluate.split_dev_test(snapshots)
    logger.info("dev=%s rows, holdout=%s rows, %d features",
                f"{len(dev):,}", f"{len(test):,}", len(feature_names))

    if tune:
        logger.info("2b/6 tuning xgboost inside the temporal CV")
        grid = models.tune_xgboost(snapshots, feature_names)
        grid.to_csv(config.REPORTS_DIR / "xgboost_tuning.csv", index=False)
        logger.info("best config: %s", grid.iloc[0]["config"])

    logger.info("3/6 cross-validation")
    cv = models.cross_validate(snapshots, feature_names)
    cv_summary = models.summarise_cv(cv)

    logger.info("4/6 holdout evaluation")
    zoo = models.build_models(feature_names)
    holdout = evaluate.evaluate_holdout(zoo, dev, test, feature_names)

    scores = {name: model.predict_proba(test[feature_names])[:, 1] for name, model in zoo.items()}
    best_name = max(scores, key=lambda n: metrics.evaluate(test["label"], scores[n])["pr_auc"])
    logger.info("best on holdout: %s", best_name)

    logger.info("5/6 diagnostics")
    best = zoo[best_name]
    importance = evaluate.permutation_table(best, test, feature_names, n_repeats=10)
    calibration = evaluate.calibration_table(test["label"], scores[best_name])
    sweep = evaluate.capacity_sweep(test["label"], scores[best_name])
    seasonality = evaluate.seasonality_check(snapshots)
    stability = evaluate.stability_check(zoo[best_name], dev, test, feature_names)

    config.MODELS_DIR.mkdir(parents=True, exist_ok=True)
    joblib.dump({"model": best, "features": feature_names, "name": best_name},
                config.MODELS_DIR / "model.joblib")

    logger.info("6/6 figures and report")
    figures = visualize.build_all(seasonality, cv, test["label"], scores, importance, sweep)
    cv.to_csv(config.REPORTS_DIR / "cv_folds.csv", index=False)
    holdout.to_csv(config.REPORTS_DIR / "holdout_metrics.csv", index=False)
    _write_report(cv_summary, holdout, seasonality, sweep, importance,
                  calibration, stability, figures, best_name)

    logger.info("Finished in %.1fs", time.time() - started)
    row = holdout[(holdout["model"] == best_name) & (holdout["split"] == "holdout (Oct+Nov)")].iloc[0]
    print(f"\nBest model  : {best_name}")
    print(f"Holdout     : PR-AUC {row['pr_auc']:.3f} | lift@20% {row['lift_at_20']:.2f}x "
          f"| precision@20% {row['precision_at_20']:.3f}")
    print(f"Model saved : models/model.joblib")
    print(f"Report      : reports/results.md  ({len(figures)} figures)")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tune", action="store_true", help="re-run the XGBoost grid search")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args()

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)-7s %(message)s", datefmt="%H:%M:%S",
    )
    run(tune=args.tune)


if __name__ == "__main__":
    main()
